package org.molgenis.emx2.graphql;

import static org.molgenis.emx2.graphql.GraphqlApiMutationResult.Status.FAILED;
import static org.molgenis.emx2.graphql.GraphqlApiMutationResult.Status.SUCCESS;

import graphql.Scalars;
import graphql.schema.GraphQLEnumType;
import graphql.schema.GraphQLFieldDefinition;
import graphql.schema.GraphQLList;
import graphql.schema.GraphQLObjectType;
import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;

@SuppressWarnings("PMD.UnusedPrivateField") // fields are read by graphql-java
public class GraphqlApiMutationResult {
  public enum Status {
    SUCCESS,
    FAILED,
    UNKNOWN
  }

  private String message;
  private Status status;
  private String taskId;
  private Map<String, String> details = new LinkedHashMap<>();
  private List<TableKeys> keys = new ArrayList<>();

  /** Primary keys of the rows a mutation touched in one table, in the order they were sent. */
  public static class TableKeys {
    private final String table;
    private final List<Map<String, Object>> keys;

    public TableKeys(String table, List<Map<String, Object>> keys) {
      this.table = table;
      this.keys = keys;
    }
  }

  public GraphqlApiMutationResult(Status status, String message, Object... formatValues) {
    this.status = status;
    this.message = String.format(message, formatValues);
  }

  public GraphqlApiMutationResult setTaskId(String taskId) {
    this.taskId = taskId;
    return this;
  }

  public GraphqlApiMutationResult addKeys(String tableId, List<Map<String, Object>> rowKeys) {
    this.keys.add(new TableKeys(tableId, rowKeys));
    return this;
  }

  public static final GraphQLEnumType enumMutationResultStatus =
      GraphQLEnumType.newEnum()
          .name("MolgenisMutationResultStatus")
          .value("SUCCESS", SUCCESS)
          .value("FAILED", FAILED)
          .build();

  public static final GraphQLObjectType typeForTableKeys =
      GraphQLObjectType.newObject()
          .name("MolgenisTableKeys")
          .field(
              GraphQLFieldDefinition.newFieldDefinition()
                  .name("table")
                  .description("Identifier of the table, as used in the mutation arguments")
                  .type(Scalars.GraphQLString)
                  .build())
          .field(
              GraphQLFieldDefinition.newFieldDefinition()
                  .name("keys")
                  .description(
                      "Primary key of each row, in the order the rows were sent, as JSON in the same"
                          + " shape as the table's query result (e.g. {\"id\":\"a1\"})")
                  .type(GraphQLList.list(GraphqlCustomTypes.GraphQLJsonAsString))
                  .build())
          .build();

  public static final GraphQLObjectType typeForMutationResult =
      GraphQLObjectType.newObject()
          .name("MolgenisResult")
          .field(
              GraphQLFieldDefinition.newFieldDefinition()
                  .name("taskId")
                  .description("Optional taskid, in case of asynchronous request")
                  .type(Scalars.GraphQLString)
                  .build())
          .field(
              GraphQLFieldDefinition.newFieldDefinition()
                  .name("status")
                  .type(enumMutationResultStatus)
                  .build())
          .field(
              GraphQLFieldDefinition.newFieldDefinition()
                  .name("message")
                  .type(Scalars.GraphQLString)
                  .build())
          .field(
              GraphQLFieldDefinition.newFieldDefinition()
                  .name("keys")
                  .description(
                      "Primary keys of the rows that were inserted, updated or saved, per table."
                          + " Includes keys generated by the database, such as AUTO_ID")
                  .type(GraphQLList.list(typeForTableKeys))
                  .build())
          .build();
}
